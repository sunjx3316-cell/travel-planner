# -*- coding: utf-8 -*-
"""景点分类:自然景观 / 人文景观 / 综合(基于名称与标签关键词)。"""
NATURE_KW = [
    "草原", "湖泊", "湖", "峡谷", "雪山", "雪峰", "湿地", "森林", "山岳", "山", "峰",
    "盐湖", "雅丹", "丹霞", "冰川", "地质", "花海", "海滩", "岛", "溶洞", "瀑布",
    "喀斯特", "自然", "沟", "湾", "河", "泉", "温泉", "海子", "林", "石林", "峰林",
    "熊猫", "动物", "生态", "公园", "大峡谷", "冰", "洞",
]
HUMAN_KW = [
    "寺", "寺院", "佛阁", "佛教", "庙", "宫", "殿", "陵", "墓", "石窟", "窟", "博物馆",
    "古城", "古镇", "古街", "古文化", "历史", "红色", "遗址", "故居", "民俗", "宗教",
    "藏寨", "村落", "村", "镇", "园林", "街区", "桥", "楼", "塔", "书院", "城",
    "乐园", "纪念馆", "文化", "庄园", "商圈", "商业街", "步行街", "广场",
]

COMPREHENSIVE_EXAMPLES = ("五台山", "武夷山", "泰山", "庐山", "黄山")


def classify_spot(name: str, tags: list = None) -> str:
    """返回 自然 / 人文 / 综合。"""
    text = f"{name} {' '.join(tags or [])}"
    n = sum(1 for k in NATURE_KW if k in text)
    h = sum(1 for k in HUMAN_KW if k in text)
    if n and h:
        return "综合"
    if n:
        return "自然"
    if h:
        return "人文"
    # 无关键词命中:名山大川默认自然,其余综合
    if any(k in name for k in COMPREHENSIVE_EXAMPLES):
        return "综合"
    return "综合"
